# paperflow/core/intent/constants.py
"""意图模块 L2 常量 registry——需重标定/重索引/改变评测口径的算法常量单一真相源。

分层判据（spec 2026-10-05 §3）：改了它需要重跑评测标定/重建索引/缓存 → 代码层
本文件；改了立即生效、对数据一致性安全 → config.yaml。本文件只收「不进 YAML」的
L2 常量。`MAX_STEPS` 因 pipeline 依赖 schemas 的单向导入约束，唯一定义在
``schemas/intent.py`` 契约层（本文件不重复定义，pipeline 直接从 schemas 取）。

每条常量固定四要素：值 / 含义与单位 / 改它的后果（要重标定？影响评测口径？）/
是否进 YAML。
"""

# ── 路由 / 澄清判据（pipeline.py 消费） ──────────────────────────────────────

#: 多标签拆分的「独立自信」余量。
#: - 值：0.05。
#: - 含义与单位：候选意图的融合分数须超过「自身标定阈值 + 本余量」才有资格拆进
#:   steps；仅仅压着阈值线过线不算数。分数为稠密/稀疏两路融合的未归一化值
#:   （截断后落 [0,1]，不是概率），本值与之同量纲。
#: - 改它的后果：必须重跑 steps/澄清标定评测（在复合句评测集上扫该值，取 steps
#:   精确率×召回率最高点）；直接改变多标签拆分口径与评测指标。
#:   标定方法说明见 pipeline.is_ambiguous / run() 第 4 级。
#: - 是否进 YAML：否（路由算法常量，非部署旋钮）。
ROUTER_STEPS_EPSILON = 0.05

#: 「贴线」澄清判据的容差。
#: - 值：0.05。
#: - 含义与单位：业务候选里分数最高者，若分数低于「自身标定阈值 + 本容差」视为
#:   不够自信（刚好压线通过或差一点没过都算），转入强制澄清轮。与 ROUTER_STEPS_EPSILON
#:   同量纲，无量纲比值。
#: - 改它的后果：改变澄清触发口径，需在复合句/歧义句评测集上重标定；影响
#:   澄清率与路由指标评测口径。
#: - 是否进 YAML：否。
CLARIFY_FLOOR_DELTA = 0.05

#: 「竞争」澄清判据的分差线。
#: - 值：0.05。
#: - 含义与单位：分数最高的两个业务候选意图分差小于此值时，认为两个都有可能、
#:   路由器无法取舍（如「这本书讲什么」落在问答与精读分析之间），让用户二选一。
#:   与上述两值同量纲。
#: - 改它的后果：改变澄清触发口径，需重标定；影响澄清率与评测指标。
#: - 是否进 YAML：否。
CLARIFY_MARGIN = 0.05

# ── 路由器装配（router.py / cli 消费） ───────────────────────────────────────

#: 生产装配的稠密分支权重 alpha。
#: - 值：0.5（两路均权）。
#: - 含义与单位：HybridRouter 凸组合中稠密路的权重，稀疏路权重为 (1 - alpha)；
#:   无量纲比值。注意 HybridRouter.__init__ 的**类默认值仍是 0.3**（偏重稀疏），
#:   生产由 CLI 装配显式传本值——类默认是历史遗留旋钮，生产永不生效。
#: - 改它的后果：改变稠密/稀疏召回配比，需重跑路由阈值 fit 标定与评测。
#: - 是否进 YAML：否；PR B 将作为 intent.router.alpha 的默认值来源（YAML 键本身
#:   不经本文件写入）。
ROUTER_ALPHA = 0.5

#: 路由器检索召回 top_k。
#: - 值：5。
#: - 含义与单位：HybridRouter 每次查询从索引取回的 utterances 条数（条），用于
#:   按路由分组聚合打分。
#: - 改它的后果：改变参与聚合的候选面，影响路由分数与阈值 fit 标定、评测口径。
#: - 是否进 YAML：否；PR B 将作为 intent.router.top_k 的默认值来源。
ROUTER_TOP_K = 5

# ── BM25 稀疏编码（encoders/bm25.py 消费） ───────────────────────────────────

#: BM25 词频饱和度参数 k1。
#: - 值：1.5。
#: - 含义与单位：控制 TF 饱和（词出现 10 次不比 5 次重要一倍）；无量纲正实数。
#: - 改它的后果：改变稀疏打分，需重跑路由阈值 fit 标定与评测。
#: - 是否进 YAML：否。
BM25_K1 = 1.5

#: BM25 文档长度归一化参数 b。
#: - 值：0.75。
#: - 含义与单位：控制文档长度归一化强度；无量纲，取值 [0,1]。
#: - 改它的后果：改变稀疏打分，需重跑路由阈值 fit 标定与评测。注意
#:   encode_documents 的分母刻意保留 b² 形式（既有行为，见 bm25.py docstring）。
#: - 是否进 YAML：否。
BM25_B = 0.75

#: BM25 query 编码的 IDF 平滑量。
#: - 值：0.5。
#: - 含义与单位：query 编码时对 df>0 加此值，避免零除与 log(0)（标准 BM25 的
#:   df+0.5 平滑）；无量纲。
#: - 改它的后果：改变 IDF 权重进而改变稀疏打分与排序，需重跑路由阈值 fit 标定与评测。
#: - 是否进 YAML：否。
BM25_IDF_SMOOTHING = 0.5

# ── fit 随机搜索超参（router.py 消费） ───────────────────────────────────────

#: fit/evaluate 的批编码大小。
#: - 值：500。
#: - 含义与单位：每批送入编码器的样本条数，避免内存过载（条）。
#: - 改它的后果：仅影响内存与耗时，不改变打分结果、无需重标定；但批量大小可能
#:   影响编码服务的吞吐表现，属运行口径。
#: - 是否进 YAML：否。
FIT_BATCH_SIZE = 500

#: fit 随机搜索的迭代次数。
#: - 值：500。
#: - 含义与单位：每轮为每个路由在当前阈值附近随机采样新阈值并评估准确率，
#:   迭代次数（轮）。
#: - 改它的后果：改变阈值搜索结果，需重跑 fit 标定（routes.yaml 阈值随之为新产物）。
#: - 是否进 YAML：否。
FIT_MAX_ITER = 500

#: fit 阈值随机搜索的采样半径。
#: - 值：0.8。
#: - 含义与单位：每个路由在 [当前阈值 - 0.8, 当前阈值 + 0.8] 内采样新阈值，
#:   截断至 [0,1]；与分数同量纲。
#: - 改它的后果：改变阈值搜索范围与最终标定产物，需重跑 fit。
#: - 是否进 YAML：否。
FIT_SEARCH_RANGE = 0.8

#: fit 阈值随机搜索的候选点数。
#: - 值：100。
#: - 含义与单位：每次采样时对搜索区间做 100 等分后随机取一点（点）。
#: - 改它的后果：改变阈值搜索粒度与最终标定产物，需重跑 fit。
#: - 是否进 YAML：否。
FIT_NUM_CANDIDATES = 100

# ── 对话层常量 ───────────────────────────────────────────────────────────────

#: 「短回复」长度上限（字符数）。
#: - 值：12。
#: - 含义与单位：routing/confirm.match_option_choice 只对不超过此长度的回复做
#:   「回复里的首个整数」宽松解析（如「选2」「我要第 3 个」）；更长文本里的整数
#:   可能是年份/图号，不当作选项号。单位：字符。
#: - 改它的后果：改变澄清回复的解析边界（可能误吞或漏解选项号），属澄清回路
#:   行为契约，需重跑澄清相关测试/评测口径。
#: - 是否进 YAML：否。
SHORT_REPLY_MAX_CHARS = 12
